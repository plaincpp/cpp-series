// example: ex01_arithmetic_operators
// purpose: Show the five arithmetic operators on two int values.
// expect: ok
// in-video: yes
#include <iostream>

int main() {
    int apples = 17;
    int boxes = 5;
    std::cout << apples + boxes << '\n';
    std::cout << apples - boxes << '\n';
    std::cout << apples * boxes << '\n';
    std::cout << apples / boxes << '\n';
    std::cout << apples % boxes << '\n';
}
